// Deterministic, non-repeating Russian filler in the register of a central-bank
// document, for the needle test.
//
// Not one paragraph repeated: a repeated block tokenises unrepresentatively and
// lets a prefix cache answer most of the prompt, which would hide both a wrong
// token count and the real prefill latency. Sentences are assembled from
// fragments with a seeded PRNG, so a given length always yields the same text.

function prng(seed) {
  let s = seed >>> 0;
  return () => { s = (s + 0x6d2b79f5) >>> 0; let t = s; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}

const SUBJ = ['Национальный Банк', 'Комитет по денежно-кредитной политике', 'Агентство по регулированию финансового рынка', 'банк второго уровня', 'микрофинансовая организация', 'страховая компания', 'Правление', 'уполномоченный орган', 'кредитное бюро', 'Министерство финансов', 'совет директоров', 'служба внутреннего аудита'];
const VERB = ['обязан обеспечить', 'вправе пересмотреть', 'ежеквартально раскрывает', 'устанавливает порядок расчёта', 'проводит оценку', 'представляет отчётность о', 'утверждает методику определения', 'осуществляет мониторинг', 'в течение десяти рабочих дней уведомляет о', 'не реже одного раза в год пересматривает'];
const OBJ = ['коэффициента достаточности собственного капитала', 'лимитов открытой валютной позиции', 'резервов по ожидаемым кредитным убыткам', 'годовой эффективной ставки вознаграждения', 'показателей ликвидности', 'долговой нагрузки заёмщика', 'операций со связанными лицами', 'концентрации кредитного риска', 'стресс-тестирования портфеля', 'минимальных резервных требований', 'процентного риска банковской книги', 'обеспечения по займам'];
const COND = ['с учётом прогноза инфляции', 'при изменении базовой ставки', 'в случае нарушения пруденциальных нормативов', 'по состоянию на первое число месяца', 'в разрезе валют и сроков погашения', 'на консолидированной основе', 'с применением коэффициентов взвешивания', 'по итогам прогнозного раунда', 'исходя из сценария умеренного шока', 'в соответствии с международными стандартами'];
const TAIL = ['Значение показателя составило {n} процента.', 'Отклонение от целевого уровня не превышает {n} п.п.', 'Объём операций достиг {n} млрд тенге.', 'Срок исполнения требования составляет {d} календарных дней.', 'Данные публикуются на официальном интернет-ресурсе.', 'Решение вступает в силу с {d} числа следующего месяца.', 'Доля просроченной задолженности снизилась до {n}%.', 'Порог существенности установлен на уровне {n} процента от капитала.'];

export function filler(chars, seed = 1) {
  const r = prng(seed);
  const pick = (a) => a[Math.floor(r() * a.length)];
  const num = () => (r() * 40 + 0.5).toFixed(1).replace('.', ',');
  const day = () => String(Math.floor(r() * 28) + 1);
  const parts = [];
  let len = 0;
  let clause = 1;
  while (len < chars) {
    let p = `${clause}.${Math.floor(r() * 9) + 1}. `;
    const k = 2 + Math.floor(r() * 3);
    for (let i = 0; i < k; i++) {
      const s = `${pick(SUBJ)} ${pick(VERB)} ${pick(OBJ)} ${pick(COND)}. ${pick(TAIL).replace('{n}', num()).replace('{d}', day())} `;
      p += s[0].toUpperCase() + s.slice(1);
    }
    parts.push(p.trim());
    len += p.length + 2;
    if (r() < 0.25) clause += 1;
  }
  return parts.join('\n\n').slice(0, chars);
}
