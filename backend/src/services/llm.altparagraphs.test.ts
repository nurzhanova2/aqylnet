import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { isMetaRemark } from './llm.service';

// The alternative wording must be text for the document, not a remark about it
// (report check of 10.11.2026). The filter is narrow: legal text legitimately
// opens with «Необходимо обеспечить…» or speaks of «документ» itself.

describe('a remark about the document is not a fragment of it', () => {
  test('the case found in project 3101, and its relatives, are remarks', () => {
    for (const t of [
      'В документе отсутствуют конкретные механизмы защиты сельских хозяйств и малых городов от ожидаемого удара по карману через рост цен на ГСМ и ЖКХ, что требует проведения парламентских слушаний.',
      'В тексте не указано, как изменятся ставки по депозитам.',
      'В данном документе нет пояснения терминов.',
      'Документ не содержит сроков пересмотра политики.',
      'Текст документа не объясняет причины решения.',
      'Необходимо добавить раздел о последствиях для заёмщиков.',
      'Следует дополнить текст примерами.',
      'Рекомендуется указать в документе пороговые значения инфляции.',
      // Project 1100: a request to the author, opening the fragment.
      'Необходимо предоставить сценарный анализ влияния повышения ставки на коэффициент просроченной задолженности (NPL) и сравнительный анализ с требованиями Базеля III.',
    ]) assert.equal(isMetaRemark(t), true, t);
  });

  test('ordinary document text is kept', () => {
    for (const t of [
      'Необходимо обеспечить устойчивость банковского сектора и защиту вкладчиков.',
      'Документ вступает в силу с 1 января 2027 года.',
      'В документе определены порядок и сроки раскрытия информации.',
      'Снижение базовой ставки до 16,25% означает, что ставки по новым кредитам могут постепенно снижаться.',
      'Следующее решение по базовой ставке будет объявлено 10 октября 2026 года.',
      'Стоит отметить, что инфляция замедляется 11 месяцев подряд.',
      // Mid-sentence «необходимо предоставить» is ordinary normative text too.
      'Для получения кредита заёмщику необходимо предоставить справку о доходах.',
      // Proposals written as text of the document stay (projects 1111, 1116).
      'Необходимо ввести прямые гарантии защиты фиксированных доходов пенсионеров от новых комиссий.',
      'В целях повышения доверия к регуляторной среде планируется внедрение механизмов строгого аудита выплат.',
    ]) assert.equal(isMetaRemark(t), false, t);
  });

  test('a Cyrillic word boundary is a real boundary', () => {
    // «нетто» must not read as «нет».
    assert.equal(isMetaRemark('В документе нетто-позиция банков приведена по состоянию на 1 сентября.'), false);
  });
});
